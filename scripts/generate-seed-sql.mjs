// Generates supabase/seed.sql from project/tenders-data.js (the cleaned
// dataset extracted from the source Excel during the design phase).
// Run with: node scripts/generate-seed-sql.mjs
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mod = await import(path.join(__dirname, "../project/tenders-data.js"));
const { TENDERS } = mod;

function sqlString(value) {
  if (value === null || value === undefined || value === "") return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlNumber(value) {
  if (value === null || value === undefined || value === "") return "null";
  const num = Number(value);
  return Number.isNaN(num) ? "null" : String(num);
}

function sqlJsonb(value) {
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
}

const rows = TENDERS.map((t) => {
  const rowNo = parseInt(t.id.replace(/\D/g, ""), 10);
  const values = [
    sqlString(t.id),
    sqlNumber(rowNo),
    sqlString(t.period),
    sqlString(t.area),
    sqlString(t.tenderNo),
    sqlString(t.customer),
    sqlString(t.product),
    sqlString(t.entitas),
    sqlNumber(t.qty),
    sqlNumber(t.oe),
    sqlNumber(t.idrPerL),
    sqlJsonb(t.milestones),
    sqlString(t.result),
    sqlString(t.carryOver),
    sqlString(t.remarks),
    sqlNumber(t.nilaiPenawaran),
  ];
  return `  (${values.join(", ")})`;
});

const sql = `-- Auto-generated by scripts/generate-seed-sql.mjs from project/tenders-data.js.
-- Do not hand-edit; regenerate if the source dataset changes.
-- Applied automatically by \`supabase db reset\` (or run manually against any
-- Postgres connection string once the schema in 0001_init.sql exists).

truncate table public.tenders;

insert into public.tenders (
  id, row_no, period, area, tender_no, customer, product, entitas,
  qty, oe, idr_per_l, milestones, result, carry_over, remarks, nilai_penawaran
) values
${rows.join(",\n")};

-- Advance the row_no sequence past the seeded rows so the next tender added
-- through the app (see src/lib/actions.ts) continues the numbering.
select setval('public.tenders_row_no_seq', (select max(row_no) from public.tenders));
`;

const outPath = path.join(__dirname, "../supabase/seed.sql");
await writeFile(outPath, sql, "utf8");
console.log(`Wrote ${rows.length} rows to ${outPath}`);
